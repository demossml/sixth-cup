-- CON-2: дни недели для показа акции.
--
-- days_mask — битовая маска, бит 0 = понедельник … бит 6 = воскресенье.
--   0b0000001 = 1   — только Пн
--   0b0011111 = 31  — будни (Пн–Пт)
--   0b1100000 = 96  — выходные (Сб, Вс)
--   0b1111111 = 127 — все дни
-- NULL = показывать все дни (поведение до этого изменения).
ALTER TABLE promos ADD COLUMN days_mask INTEGER;

-- Существующие акции остаются «на все дни».
UPDATE promos SET days_mask = NULL;
