-- CON-4: как показывать изображение акции.
--
-- image_fit = 'contain' — готовый плакат (вертикальный постер) показывается целиком,
--   по бокам мягкая брендовая подложка. Ничего не обрезается.
-- image_fit = 'cover' — обычное фото товара заполняет кадр 4:5, лишнее обрезается.
--
-- По умолчанию 'contain': безопаснее, потому что существующие материалы —
-- готовые постеры 2:3 с текстом, и обрезка убивает их смысл.
ALTER TABLE promos ADD COLUMN image_fit TEXT NOT NULL DEFAULT 'contain';
