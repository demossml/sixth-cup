-- CON-3: у акции появляются отдельные поля вместо одного «текста на всё».
--
-- subtitle — короткое описание для карточки на главной;
-- body     — полное описание для модального окна;
-- terms    — условия мелким шрифтом внизу окна.
--
-- Причина: владелец вставлял весь текст в одно поле вместе с подписями формы
-- («Краткое описание», «Полное описание для карточки»), и гости видели это
-- на карточке.
ALTER TABLE promos ADD COLUMN subtitle TEXT;
ALTER TABLE promos ADD COLUMN terms TEXT;

-- Действующие материалы не меняем: карточка продолжит показывать body,
-- пока владелец не заполнит короткое описание.
