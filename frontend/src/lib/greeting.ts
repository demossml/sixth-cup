/**
 * Приветствие по времени суток (Luckin-приём: строка стоит одну строку, а
 * создаёт ощущение «это моё приложение»).
 *
 * Границы: 05–11 утро, 12–16 день, 17–22 вечер, 23–04 ночь.
 * Функция чистая и принимает дату параметром — тестируется без моков таймера.
 */
export function greetingFor(date: Date = new Date()): string {
  const h = date.getHours()
  if (h >= 5 && h < 12) return 'Доброе утро'
  if (h >= 12 && h < 17) return 'Добрый день'
  if (h >= 17 && h < 23) return 'Добрый вечер'
  return 'Доброй ночи'
}
