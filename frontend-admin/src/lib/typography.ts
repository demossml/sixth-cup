/**
 * Типографика для печати: короткие правила, которые убирают «сироты» в меню.
 *
 * Неразрывный пробел не даёт единице измерения, тире и открывающей кавычке
 * оказаться в начале строки. Работает одинаково на холсте и в PDF — иначе
 * превью и типография разойдутся.
 */

const NBSP = '\u00A0'

/** «250 мл» → «250 мл», «— 169 ₽» → «— 169 ₽», «« Капучино» → ««Капучино». */
export function typograph(input: string | null | undefined): string {
  if (!input) return ''
  let t = input

  // Число + единица измерения / валюта: не разрываем.
  t = t.replace(/(\d)\s+(мл|л|г|кг|шт|порц|руб|₽)/gi, `$1${NBSP}$2`)

  // Открывающая кавычка не должна висеть в конце строки, закрывающая — начинать её.
  t = t.replace(/\s+«/g, `${NBSP}«`)
  t = t.replace(/«\s+/g, '«')
  t = t.replace(/\s+»/g, '»')
  t = t.replace(/»\s+/g, `»${NBSP}`)
  t = t.replace(/\s+\(/g, `${NBSP}(`)

  // Тире в начале строки — плохо: приклеиваем к предыдущему слову.
  t = t.replace(/\s+—\s+/g, `${NBSP}— `)

  // Лишние пробелы в начале и в конце.
  return t.replace(/^ +| +$/g, '')
}

/** Сколько «строк-сирот» останется при таком переносе — для тестов и отладки. */
export const hasHangingPunctuation = (s: string): boolean => /\n\s*[»)—–]/.test(s)
